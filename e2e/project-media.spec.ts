import { expect, test } from '@playwright/test'

test('music-content resume keeps project media compact and opens an accessible gallery', async ({ page }) => {
  const fullImageRequests: string[] = []
  page.on('request', request => {
    if (request.url().includes('/images/resume/chinese-heritage-concert/') && !request.url().includes('/thumbs/')) fullImageRequests.push(request.url())
  })

  await page.goto('/music-content/resume')
  const project = page.locator('#projects article').filter({ hasText: '谢菲尔德大学中国作品专场音乐会' })
  const toggle = project.locator('.project-media-heading button')
  await expect(toggle).toHaveAccessibleName('展开 6 张影像')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(project.locator('.project-media-preview')).toHaveCount(0)
  await toggle.click()
  await expect(project.getByRole('button', { name: '收起影像' })).toHaveAttribute('aria-expanded', 'true')
  await expect(project.locator('.project-media-tile')).toHaveCount(3)
  expect(await project.locator('.project-media-tile img').evaluateAll(images => images.every(image => getComputedStyle(image).objectFit === 'contain'))).toBe(true)
  expect(fullImageRequests).toEqual([])

  const openButton = project.getByRole('button', { name: /查看演出结束后的全体谢幕/ })
  await openButton.click()
  const dialog = page.getByRole('dialog', { name: '谢菲尔德大学中国作品专场音乐会' })
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('.project-media-counter')).toHaveText('01 / 06')
  expect(await dialog.locator('.project-media-thumbnails img').evaluateAll(images => images.every(image => getComputedStyle(image).objectFit === 'contain'))).toBe(true)
  const firstImage = dialog.getByRole('img', { name: /演职人员在谢菲尔德 Firth Hall 舞台合影/ })
  await expect(firstImage).toBeVisible()
  await expect.poll(() => firstImage.evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await page.waitForTimeout(300)
  await dialog.screenshot({ path: '.artifacts/project-media-desktop-dialog.png' })
  await expect.poll(() => fullImageRequests.length).toBeGreaterThan(0)

  await dialog.getByRole('button', { name: '查看下一张图片' }).click()
  await expect(dialog.locator('.project-media-counter')).toHaveText('02 / 06')
  await expect(dialog.getByRole('img', { name: /2025 年 3 月 19 日/ })).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(dialog.locator('.project-media-counter')).toHaveText('03 / 06')
  await dialog.getByRole('button', { name: '查看第 6 张：活动团队合影' }).click()
  await expect(dialog.locator('.project-media-counter')).toHaveText('06 / 06')
  await expect(dialog.getByRole('img', { name: '中国作品音乐会活动团队合影照片' })).toBeVisible()

  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(openButton).toBeFocused()
  await project.getByRole('button', { name: '收起影像' }).click()
  await expect(project.locator('.project-media-preview')).toHaveCount(0)
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
})

