test('Chinese New Year project reuses the gallery with a balanced three-image preview', async ({ page }) => {
  await page.goto('/music-content/resume')
  const project = page.locator('#projects article').filter({ hasText: '谢菲尔德市华人春节联欢晚会' })
  await project.getByRole('button', { name: '展开 3 张影像' }).click()
  const preview = project.locator('.project-media-preview')
  await expect(preview).toHaveAttribute('data-count', '3')
  await expect(preview.locator('.project-media-tile')).toHaveCount(3)
  await preview.scrollIntoViewIfNeeded()
  await expect.poll(() => preview.locator('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
  await project.locator('.project-media').screenshot({ path: '.artifacts/chinese-new-year-media-desktop.png' })
  await project.getByRole('button', { name: /查看持场内工作证参与现场执行/ }).click()
  const dialog = page.getByRole('dialog', { name: '谢菲尔德市华人春节联欢晚会' })
  await expect(dialog.locator('.project-media-counter')).toHaveText('01 / 03')
  const crewImage = dialog.getByRole('img', { name: /场内工作证并手持对讲机/ })
  await expect.poll(() => crewImage.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await page.waitForTimeout(300)
  const crewLayout = await crewImage.evaluate(element => {
    const image = element as HTMLImageElement
    const imageBounds = image.getBoundingClientRect()
    const figureBounds = image.parentElement!.getBoundingClientRect()
    return {
      image: { width: imageBounds.width, height: imageBounds.height },
      figure: { width: figureBounds.width, height: figureBounds.height },
      objectFit: getComputedStyle(image).objectFit,
    }
  })
  expect(crewLayout.objectFit).toBe('contain')
  expect(crewLayout.image.width).toBeCloseTo(crewLayout.figure.width, 1)
  expect(crewLayout.image.height).toBeCloseTo(crewLayout.figure.height, 1)
  await dialog.screenshot({ path: '.artifacts/chinese-new-year-media-dialog.png' })
  await dialog.getByRole('button', { name: '查看下一张图片' }).click()
  await expect(dialog.locator('.project-media-counter')).toHaveText('02 / 03')
  await expect(dialog.getByRole('img', { name: /当地摄影师在社交平台发布/ })).toBeVisible()
  await dialog.getByRole('button', { name: '查看第 3 张：春晚工作感谢证书' }).click()
  await expect(dialog.locator('.project-media-counter')).toHaveText('03 / 03')
  await expect(dialog.getByRole('img', { name: /2025 谢菲尔德华人春节活动工作感谢证书/ })).toBeVisible()
})

test('project media remains readable without lengthening the mobile resume', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 720 })
  await page.goto('/music-content/resume')
  const gallery = page.locator('.project-media').first()
  await gallery.getByRole('button', { name: '展开 6 张影像' }).click()
  await expect(gallery.locator('.project-media-preview')).toHaveCSS('height', '132px')
  const secondGallery = page.locator('.project-media').nth(1)
  await secondGallery.getByRole('button', { name: '展开 3 张影像' }).click()
  await expect(secondGallery.locator('.project-media-preview')).toHaveCSS('height', '132px')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await gallery.scrollIntoViewIfNeeded()
  await expect.poll(() => gallery.locator('.project-media-preview img').evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
  await gallery.screenshot({ path: '.artifacts/project-media-mobile-preview.png' })
  await secondGallery.scrollIntoViewIfNeeded()
  await expect.poll(() => secondGallery.locator('.project-media-preview img').evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
  await secondGallery.screenshot({ path: '.artifacts/chinese-new-year-media-mobile.png' })

  await gallery.getByRole('button', { name: /查看演出结束后的全体谢幕/ }).click()
  const dialog = page.getByRole('dialog', { name: '谢菲尔德大学中国作品专场音乐会' })
  await expect(dialog).toBeVisible()
  const image = dialog.getByRole('img', { name: /演职人员在谢菲尔德 Firth Hall 舞台合影/ })
  await expect.poll(() => image.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await expect(dialog.getByRole('status', { name: '正在载入影像' })).toHaveCount(0)
  await page.waitForTimeout(300)
  const bounds = await dialog.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(320)
  expect(bounds!.y).toBeGreaterThanOrEqual(0)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(720)
  await page.screenshot({ path: '.artifacts/project-media-mobile-dialog.png' })
})

test('project media exposes a retry when a full image cannot load', async ({ page }) => {
  await page.route('**/01-stage-finale.jpg*', route => route.abort())
  await page.goto('/music-content/resume')
  const project = page.locator('#projects article').filter({ hasText: '谢菲尔德大学中国作品专场音乐会' })
  await project.getByRole('button', { name: '展开 6 张影像' }).click()
  await project.getByRole('button', { name: /查看演出结束后的全体谢幕/ }).click()
  const dialog = page.getByRole('dialog', { name: '谢菲尔德大学中国作品专场音乐会' })
  await expect(dialog.getByRole('alert')).toContainText('影像暂时无法载入')
  await page.unroute('**/01-stage-finale.jpg*')
  await dialog.getByRole('button', { name: '重新加载' }).click()
  const image = dialog.getByRole('img', { name: /演职人员在谢菲尔德 Firth Hall 舞台合影/ })
  await expect.poll(() => image.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await expect(dialog.getByRole('alert')).toHaveCount(0)
})
